#!/usr/bin/env python3
"""Build img/ and data/levels.js from the teacher's PDF + the marking-tool JSON.

  python3 tools/build.py deck.pdf marks.json

Needs poppler's `pdftoppm` and Pillow.  Re-run it whenever the marks change
(for example when the holiday pages get marked).
"""
import json, os, re, subprocess, sys, tempfile
from collections import Counter
from PIL import Image

DPI = 132
K = DPI / 110                      # crop boxes below were measured at 110 dpi
CROPS = {                          # box inside the page, with borders / titles / crop marks removed
    'General': None,
    'Calendar': (34, 81, 1254, 857),
    'Months': (34, 81, 1254, 857),
    'Holidays': (90, 65, 1196, 846),
}
GAME_GROUP = {'General': 'general', 'Calendar': 'months', 'Months': 'months', 'Holidays': 'holidays'}
GROUPS = [
    {'id': 'months', 'title': 'Months', 'ja': 'つきの なまえ', 'mode': 'spell',
     'hint': 'Find the letters in order to spell the month!'},
    {'id': 'general', 'title': 'Find all 26 letters', 'ja': '26もじ ぜんぶ さがそう', 'mode': 'alphabet',
     'hint': 'Every picture hides A to Z.'},
    {'id': 'holidays', 'title': 'Holidays', 'ja': 'ぎょうじ', 'mode': 'spell',
     'hint': 'Find the letters in order to spell the word!'},
]

def main(pdf, marks_path, out='.'):
    marks = json.load(open(marks_path, encoding='utf-8'))
    fixes = json.load(open(os.path.join(os.path.dirname(__file__), 'fixes.json'), encoding='utf-8'))
    os.makedirs(os.path.join(out, 'img', 'thumbs'), exist_ok=True)
    os.makedirs(os.path.join(out, 'data'), exist_ok=True)
    levels = []
    with tempfile.TemporaryDirectory() as tmp:
        for lv in marks['levels']:
            if not lv['letters']:
                print('skip (no letters yet):', lv['id']); continue
            gid = GAME_GROUP[lv['group']]
            letters = [dict(l=a['letter'].upper(), cx=a['cx'], cy=a['cy'], rx=a['rx'], ry=a['ry']) for a in lv['letters']]
            for fx in fixes:                      # corrections for mistyped keys
                if fx['id'] != lv['id']: continue
                m = min(letters, key=lambda m: (m['cx'] - fx['near'][0]) ** 2 + (m['cy'] - fx['near'][1]) ** 2)
                assert m['l'] == fx['was'].upper(), (lv['id'], m['l'], fx)
                m['l'] = fx['letter'].upper()
            mt = re.match(r'^(.*?)\s*\((.*)\)\s*$', lv['title'])
            title, ja = (mt.group(1), mt.group(2)) if mt else (lv['title'], '')
            word = title if GROUPS[[g['id'] for g in GROUPS].index(gid)]['mode'] == 'spell' else None
            if word:
                need = Counter(word.upper()); got = Counter(m['l'] for m in letters)
                if need - got: print('WARNING', lv['id'], 'missing letters for', word, dict(need - got))
                if got - need: print('note', lv['id'], 'has extra letters', dict(got - need))
            else:
                if sorted(m['l'] for m in letters) != list('ABCDEFGHIJKLMNOPQRSTUVWXYZ'):
                    print('WARNING', lv['id'], 'is not exactly A-Z')
            page = lv['pdfPuzzlePage']
            base = os.path.join(tmp, 'p')
            subprocess.run(['pdftoppm', '-r', str(DPI), '-f', str(page), '-l', str(page), '-png', '-singlefile', pdf, base], check=True)
            im = Image.open(base + '.png').convert('RGB')
            box = CROPS[lv['group']]
            if box: im = im.crop(tuple(round(v * K) for v in box))
            im.save(os.path.join(out, 'img', lv['id'] + '.webp'), 'WEBP', quality=88, method=6)
            th = im.resize((420, round(420 * im.height / im.width)), Image.LANCZOS)
            th.save(os.path.join(out, 'img', 'thumbs', lv['id'] + '.webp'), 'WEBP', quality=80, method=6)
            levels.append(dict(id=lv['id'], group=gid, title=title, ja=ja, word=word,
                               image='img/%s.webp' % lv['id'], thumb='img/thumbs/%s.webp' % lv['id'],
                               w=im.width, h=im.height,
                               letters=[dict(l=m['l'], cx=round(m['cx'], 4), cy=round(m['cy'], 4), rx=round(m['rx'], 4), ry=round(m['ry'], 4)) for m in letters]))
    used = {l['group'] for l in levels}
    data = {'version': 1, 'groups': [g for g in GROUPS if g['id'] in used], 'levels': levels}
    with open(os.path.join(out, 'data', 'levels.js'), 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/build.py - do not edit by hand.\nwindow.HL_DATA = ' + json.dumps(data, ensure_ascii=False, indent=1) + ';\n')
    print('levels:', len(levels))

if __name__ == '__main__':
    if len(sys.argv) < 3: sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else '.')
